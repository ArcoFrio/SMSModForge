"""Which expression variable each of the game's busts watches, into Shared/VanillaBustWatches.cs.

    python Tools/Research/Variables/bust_watches.py Tools/Research/Variables/runs/<date>

Every expressive bust has a trigger under <bust>/MBase1/Expressions that copies ONE variable of the
Expressions list into Currently-Chosen on any variable change, and its Conditions show the face that number
names. The plugin set the SPEAKER's variable, and some busts watch another: Chloe's watch Charlotte's,
Cerise's (Android_*) Anna's, Nadia's Emma's; a face given to them reverted at once (found by the variable
research, 1.9.0). The table is read from refs.tsv: the "Set Expressions[Currently-Chosen] =
Expressions[X]" instruction on each bust's Expressions trigger. Stops, writing nothing, when a bust
copies two different variables, or an expressive bust (Shared/VanillaBustExpressions.cs) has none.
"""
import csv, os, re, sys

run = sys.argv[1]
sys.stdout.reconfigure(encoding="utf-8")
root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
copy = re.compile(r"Set Expressions\[Currently-Chosen\] = Expressions\[([^\]]+)\]")
watches, problems = {}, []
with open(os.path.join(run, "game", "refs.tsv"), encoding="utf-8") as f:
    for r in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE):
        where = r["root"]
        if not where.startswith("2_Bust_Manager/") or r["list"] != "Expressions":
            continue
        m = copy.search(r["context"])
        if not m or r["variable"] != m.group(1):
            continue
        bust = where.split("/")[1]
        watches.setdefault(bust, set()).add(m.group(1))

with open(os.path.join(root, "Shared", "VanillaBustExpressions.cs"), encoding="utf-8") as f:
    src = f.read()
block = src[src.find("HashSet<string> Expressive ="):]
block = block[block.find("\n        {"):]
expressive = set(re.findall(r'"([^"]+)"', block[:block.find("};")]))
for bust, names in sorted(watches.items()):
    if len(names) > 1:
        problems.append("%s copies %s" % (bust, ", ".join(sorted(names))))
# An expressive bust with no copy instruction follows no variable (Robert's, Clay's: their Expressions
# trigger only opens the mouth), so a face switched on by name stays: listed with an empty name.
follows_none = sorted(b for b in expressive if b not in watches)
for b in follows_none:
    watches[b] = {""}
if problems:
    print("nothing written:")
    for p in problems:
        print("  " + p)
    sys.exit(1)

out = ["// GENERATED by Tools/Research/Variables/bust_watches.py from the variable research's refs.tsv.",
       "// Do not edit by hand.",
       "using System.Collections.Generic;", "",
       "namespace SMSModForge.Shared", "{",
       "    /// <summary>",
       "    /// Which number each of the game's expressive busts shows its face by: the variable of the",
       "    /// Expressions list its own trigger copies into Currently-Chosen on every variable change.",
       "    /// <para/>",
       "    /// Usually the character's own, but not always: Chloe's busts copy Charlotte's, Cerise's",
       "    /// (Android_*) Anna's, Nadia's Emma's. A face a pack gives one of those has to be written to",
       "    /// THAT variable, or the trigger puts the old face back at the next variable write (1.9.0;",
       "    /// before, the speaker's own was written). Compiled into both projects, like",
       "    /// <see cref=\"VanillaBustExpressions\"/>.",
       "    /// </summary>",
       "    public static class VanillaBustWatches",
       "    {",
       "        private static readonly Dictionary<string, string> Watched = new Dictionary<string, string>(System.StringComparer.Ordinal)",
       "        {"]
out += ['            ["%s"] = "%s",' % (b, sorted(n)[0]) for b, n in sorted(watches.items())]
out += ["        };", "",
        "        /// <summary>The variable this bust's face follows; empty for one whose face follows none (its",
        "        /// trigger copies nothing, so a face switched on stays); null for a bust not in the table.</summary>",
        "        public static string VariableOf(string bustGoName)",
        "        {",
        "            return !string.IsNullOrEmpty(bustGoName) && Watched.TryGetValue(bustGoName, out var v) ? v : null;",
        "        }",
        "    }", "}", ""]
with open(os.path.join(root, "Shared", "VanillaBustWatches.cs"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print("written: %d busts (%d follow no variable: %s), %d expressive in the art table; %d follow another's" % (
    len(watches), len(follows_none), ", ".join(follows_none), len(expressive),
    sum(1 for b, n in watches.items() if next(iter(n)) and not b.lower().startswith(next(iter(n)).lower()[:3]))))

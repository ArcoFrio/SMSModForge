REWORDED = {"maskStudio.soften", "maskStudio.soften.tip"}

for code, texts in T.items():
    assert len(texts) == len(KEYS), (code, len(texts))
    folder = os.path.join(HERE, code)
    os.makedirs(folder, exist_ok=True)
    with io.open(os.path.join(folder, "maskstudio.txt"), "w", encoding="utf-8", newline="\n") as f:
        for key, text in zip(KEYS, texts):
            if key in REWORDED: continue   # reworded since: written by write_softenbrush.py
            f.write(key + " = " + text + "\n")
    print(code, len(texts))
